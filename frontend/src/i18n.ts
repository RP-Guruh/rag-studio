function initialLocale(): Locale {
  if (typeof localStorage !== 'undefined') {
    const stored = localStorage.getItem('rag_studio_locale')
    if (stored === 'id' || stored === 'en') return stored
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('id')) {
    return 'id'
  }
  return 'en'
}

export const locale = ref<Locale>(initialLocale())

export function setLocale(value: Locale) {
  locale.value = value
  if (typeof localStorage !== 'undefined') localStorage.setItem('rag_studio_locale', value)
}

export function t(key: string, params?: Record<string, string | number>): string {
  const translate = dictionary[locale.value]?.[key] ?? key
  if (!params) return translate
  return translate.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(params[name] ?? ''))
}
